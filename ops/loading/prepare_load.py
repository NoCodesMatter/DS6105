"""Check a pair of stage manifests and generate an atomic psql bulk-load script.

Python 3.10+, standard library only. Database credentials are handled by psql.
Run the HDB and spatial verifiers before preparing an import.
"""
import argparse
import csv
import hashlib
import importlib.util
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
spec = importlib.util.spec_from_file_location("housing_contract", ROOT / "db/schema/contract.py")
contract = importlib.util.module_from_spec(spec)
spec.loader.exec_module(contract)
SPATIAL_TABLES = {"hdb_building", "hawker_centre", "building_hawker"}


def require(condition, message):
    if not condition:
        raise ValueError(message)


def sha256(path):
    digest = hashlib.sha256()
    with path.open("rb") as source:
        for chunk in iter(lambda: source.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def literal(value):
    require(not any(c in value for c in "\r\n\x00"), "Invalid newline or NUL in SQL value")
    return "'" + value.replace("'", "''") + "'"


def prepare(hdb_stage, spatial_stage, output):
    hdb_stage, spatial_stage = hdb_stage.resolve(), spatial_stage.resolve()
    hdb_manifest = hdb_stage / "manifest.json"
    hdb = json.loads(hdb_manifest.read_text(encoding="utf-8"))
    spatial = json.loads((spatial_stage / "manifest.json").read_text(encoding="utf-8"))
    for manifest in (hdb, spatial):
        require(manifest["contract_version"] == contract.VERSION, "Stage contract version mismatch")
    require(hdb["status"] == "ready_for_hdb_handoff", "HDB stage is not ready")
    require(spatial["status"] == "ready_for_integration", "Spatial stage is not ready")
    require(spatial["hdb_stage"]["manifest_sha256"] == sha256(hdb_manifest),
            "Spatial outputs belong to a different HDB stage")
    require(hdb["fatal_records"] == hdb["dropped_records"] == 0,
            "HDB stage has unresolved fatal or dropped records")
    require(hdb["tables"]["hdb_building"]["rows"] == spatial["tables"]["hdb_building"]["rows"],
            "Building handoff count mismatch")

    checks, copies, summary = [], [], []
    tables = ", ".join("housing." + t for t in contract.LOAD_ORDER)
    for table in contract.LOAD_ORDER:
        directory, manifest = (spatial_stage, spatial) if table in SPATIAL_TABLES else (hdb_stage, hdb)
        path = directory / (table + ".csv")
        metadata = manifest["tables"][table]
        require(path.stat().st_size == metadata["bytes"] and sha256(path) == metadata["sha256"],
                f"CSV differs from manifest: {path}")
        with path.open(encoding="utf-8", newline="") as source:
            require(tuple(next(csv.reader(source))) == contract.CSV_COLUMNS[table],
                    f"Incorrect CSV header: {path}")
        expected = metadata["rows"]
        require(type(expected) is int and expected > 0, f"Invalid count for {table}")
        columns = ", ".join(contract.CSV_COLUMNS[table])
        copies.append(f"\\copy housing.{table} ({columns}) FROM {literal(path.as_posix())} "
                      "WITH (FORMAT csv, HEADER MATCH, NULL '', ENCODING 'UTF8')")
        checks.append(f"IF (SELECT count(*) FROM housing.{table}) <> {expected} THEN "
                      f"RAISE EXCEPTION 'Unexpected row count: {table} (expected {expected})'; END IF;")
        summary.append(f"SELECT '{table}' AS table_name, count(*) AS rows FROM housing.{table}")

    # The shared validator owns its transaction when run directly. Embed its
    # unchanged acceptance checks inside OUR transaction, before committing COPY.
    validation = (ROOT / "db/schema/validate_loaded_data.sql").read_text(encoding="utf-8")
    begin = "BEGIN TRANSACTION ISOLATION LEVEL REPEATABLE READ READ ONLY;"
    require(validation.count(begin) == 1 and validation.count("COMMIT;") == 1
            and validation.rstrip().endswith("COMMIT;"), "Shared validator transaction wrapper changed")
    validation = validation.replace(begin, "").rsplit("COMMIT;", 1)[0]
    empty_condition = " OR ".join(f"EXISTS (SELECT FROM housing.{t})" for t in contract.LOAD_ORDER)
    sql = "\n".join([
        "-- Generated by ops/loading/prepare_load.py; validated stage: " + literal(hdb["stage"]),
        "-- Empty database only. Any COPY/check error aborts the entire import.",
        "\\set ON_ERROR_STOP on",
        "BEGIN;",
        "SET LOCAL standard_conforming_strings = on;",
        "SET LOCAL client_encoding = 'UTF8';",
        f"LOCK TABLE {tables} IN ACCESS EXCLUSIVE MODE;",
        f"DO $$ BEGIN IF {empty_condition} THEN "
        "RAISE EXCEPTION 'Target tables are not empty; use a new stage database'; END IF; END $$;",
        *copies,
        "DO $$ BEGIN\n" + "\n".join(checks) + "\nEND $$;",
        validation,
        *[f"ANALYZE housing.{t};" for t in contract.LOAD_ORDER],
        "\nUNION ALL\n".join(summary) + ";",
        "COMMIT;",
        "",
    ])
    output.parent.mkdir(parents=True, exist_ok=True)
    with output.open("x", encoding="utf-8", newline="\n") as destination:
        destination.write(sql)
    print(f"Prepared: {output.resolve()}")
    print("CSV hashes and headers passed; no database connection or import has been executed.")
    print("Run this file with psql -X -v ON_ERROR_STOP=1 -f <file> against an empty stage database.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--hdb-stage", type=Path, required=True)
    parser.add_argument("--spatial-stage", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    prepare(args.hdb_stage, args.spatial_stage, args.output)
